function bbArcade(api) {
  const FK = FrontKit(api, { mp: true, goSound: () => { try { Sound.bbPick(); } catch (e) {} } });
  const host = {
    FK,
    /* the party's match, when this mount is one */
    net: api.entry === 'play' ? getSession('brawl') : null,
    left() { api.gameOver({ score: 0, title: 'Host left', message: 'The match ended when the host left.', stats: [] }); },
    /* the end of a match: against the computer it adds to (or ends) the
       win streak, which is the score; online is for the fun of it */
    end(r) {
      let streak = api.load('streak', 0), score = 0;
      if (!r.online) {
        streak = r.win ? streak + 1 : 0;
        api.save('streak', streak);
        score = r.win ? streak : 0;
      }
      r.streak = streak;
      const won = 3 - r.theirs, lost = 3 - r.mine;
      const stats = [{ label: 'Rounds', value: won + ' - ' + lost }];
      if (r.big) stats.push({ label: 'Biggest hit', value: String(Math.round(r.big)) });
      api.gameOver({
        score, win: r.win,
        title: r.win ? 'Victory' : 'Defeat',
        message: won + '–' + lost + (r.online ? ' against ' + r.them : ' against the computer'),
        stats, brawl: r, sting: false
      });
    }
  };
  const game = bbMatch(api, host);
  const U = game.U, C = U.C;

  /* ---- the results page, in the game's look ---- */
  let heroBalls = [];
  const THEME = {
    top: 20, gap: 14, colL: 250, colR: 400, btnH: 52, foot: 38, wide: 240, narrow: 140, statH: 56,
    veil(ctx, k) { ctx.fillStyle = 'rgba(6,8,20,' + (.84 * k).toFixed(3) + ')'; ctx.fillRect(0, 0, 960, 600); },
    hero(ctx, cx, top) {
      const R = FK.R, r = (R.res && R.res.brawl) || {}, t = FK.rt();
      const left = R.res && R.res.title === 'Host left';
      const word = left ? 'HOST LEFT' : r.win ? 'VICTORY' : 'DEFEAT';
      U.stamp(ctx, word, cx, top + 46, t, { size: 82, col: r.win ? '#fff4c2' : '#e8e8f0', glow: r.win ? C.gold : '#ff4d6d', stagger: .05 });
      const k = FK.eo(FK.rs('sub', undefined, .4)), y = top + 118;
      heroBalls = [];
      if (k > 0 && r.picks) {
        ctx.save(); ctx.globalAlpha *= k; ctx.translate(0, (1 - k) * 12);
        const won = 3 - r.theirs, lost = 3 - r.mine;
        U.disp(ctx, won + ' – ' + lost, cx, y, 48, C.ink, 'center', { shadow: 'rgba(0,0,0,.6)', sy: 3.5 });
        U.ribbon(ctx, r.online ? 'Against ' + r.them : 'Against the computer', cx, y + 36, 10, '#c9d3f2', 'center', { rule: 34 });
        ctx.restore();
        heroBalls.push({ id: r.picks[0], x: cx - 150 - (1 - k) * 40, y: y + 4, size: 92, turn: t * 1.3, roll: t * .5, alpha: k });
        heroBalls.push({ id: r.picks[1], x: cx + 150 + (1 - k) * 40, y: y + 4, size: 92, turn: -t * 1.3, roll: t * .5, alpha: k });
        U.pill(ctx, 'You', cx - 150, y + 58, { col: '#ffffff', fill: mixHex(C.me, '#000000', .5), edge: C.me, size: 9.5, h: 22, alpha: k });
        U.pill(ctx, r.online ? r.them : 'Computer', cx + 150, y + 58, { col: '#ffffff', fill: mixHex(C.them, '#000000', .5), edge: C.them, size: 9.5, h: 22, alpha: k });
      }
      const g = FK.rs('tag', undefined, .45), ty = y + 80;
      if (g > 0 && r.picks && !r.online) {
        if (R.isBest) {
          const s = g < 1 ? FK.bo(g) : 1 + Math.sin(FK.t * 5) * .03;
          ctx.save(); ctx.translate(cx, ty); ctx.scale(s, s);
          const w = 210;
          const gr = ctx.createLinearGradient(0, -16, 0, 16); gr.addColorStop(0, '#ffe07a'); gr.addColorStop(1, '#ff9f1c');
          ctx.fillStyle = gr; rr(ctx, -w / 2, -16, w, 32, 16); ctx.fill();
          U.disp(ctx, 'NEW BEST STREAK', 0, 1, 20, '#26160a', 'center', { track: 1 });
          ctx.restore();
        } else if (r.win || R.best) U.pill(ctx, r.win ? 'Win streak  ' + r.streak : 'Best streak  ' + R.best, cx, ty, { icon: r.win ? 'flame' : 'cup', iconCol: r.win ? '#ff9f1c' : C.gold, col: r.win ? C.gold : C.ink, alpha: FK.eo(g) });
      }
      return ty + 16 - top;
    },
    stat(ctx, st, x, y, w, h) {
      U.panel(ctx, x, y, w, h, { shadow: false });
      U.caps(ctx, st.label, x + 18, y + h / 2, 9.5, C.mute);
      U.disp(ctx, String(st.value), x + w - 18, y + h / 2 + 1, 28, C.ink, 'right');
    },
    card(ctx, x, y, w, h) { U.panel(ctx, x, y, w, h, { shadow: false }); },
    head(ctx, x, y, w) {
      U.caps(ctx, 'Coins', x, y, 9.5, C.mute);
      U.disp(ctx, fmt(FK.purse()), x + w, y + 1, 24, C.gold, 'right', { it: false, w: 700, shadow: 'rgba(0,0,0,.45)', sy: 1.5 });
    },
    pad: 20, headH: 44,
    ls: {
      text(ctx, s, x, y, size, col, align) { U.disp(ctx, String(s), x, y + 1, size * 1.2, col, align || 'left', { it: false, w: 700, shadow: 'rgba(0,0,0,.45)', sy: 1.2 }); },
      label(ctx, s, x, y, size, col, align) { U.caps(ctx, s, x, y, size * .9, col, align || 'left'); },
      measure(ctx, s, size) { return U.dispW(ctx, String(s), size * 1.2, { w: 700 }); },
      ink: C.ink, mute: C.mute, gold: C.gold, rule: 'rgba(255,255,255,.12)', bar: 'rgba(255,255,255,.1)', fill: C.gold,
      rowH: 24, size: 14, lsize: 11, totalSize: 26, totalH: 38, xpH: 40, noteH: 22, barH: 8
    },
    get againLabel() { return FK.mode() === 'guest' ? 'HOST STARTS' : 'PLAY AGAIN'; },
    button(ctx, key, label, x, y, w, h, primary) {
      const wait = key === 'again' && FK.mode() === 'guest';
      const b = wait ? { h: 0, p: 0 } : FK.btn(key, x, y, w, h);
      U.button(ctx, key, x, y, w, h, label, { b, primary: primary && !wait, live: !wait, size: h * .42 });
    },
    hint(ctx, cx, y) {
      const keys = FK.mode() === 'guest' ? [['BKSP', 'Hub']]
        : [['SPACE', 'Play again']].concat(FK.R && FK.R.menuOk ? [['M', 'Menu']] : [], [['BKSP', 'Hub']]);
      U.hints(ctx, keys, cx, Math.min(y + 4, 584), { h: 17 });
    }
  };

  return {
    update(dt) { if (!FK.R) game.update(dt); },
    render(ctx) {
      FK.frame();
      game.P.hudOff = !!FK.R;
      game.render(ctx);
      if (FK.R) {
        FK.resultsPage(ctx, 960, 600, THEME);
        if (heroBalls.length) game.preview(heroBalls, ctx, performance.now() / 1000);
      }
    },
    destroy() { FK.done(); game.destroy(); },
    escape() { return game.escape(); },
    results(R) { FK.showResults(R, { sounds: { up: () => { try { Sound.clearEnd(3); } catch (e) {} } } }); },
    /* for tests driven from the page, as golf and soccer do it */
    _dev: { game, FK }
  };
}
